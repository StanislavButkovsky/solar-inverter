// Кнопка BOOT на плате как пользовательская: перевод Wi-Fi в режим точки доступа.
//
// BOOT висит на GPIO0 и нужна загрузчику: если она нажата в момент сброса или
// подачи питания, чип уходит в режим прошивки и программа не стартует. После
// загрузки нога свободна, на ней внутренняя подтяжка, и читать её можно как
// обычный вход — нажатие это низкий уровень. Единственное, чего с ней делать
// нельзя, — держать нажатой при включении и вешать на неё выход.
//
//   короткое нажатие  — включить или выключить точку доступа solar-setup
//   удержание 8 c     — сброс всех настроек и перезагрузка
//
// Светодиод на плате: горит — точка доступа поднята, не горит — обычный режим
// клиента. Пока кнопка удерживается дольше восьми секунд, часто мигает: это
// предупреждение о сбросе. Отпустить раньше — ничего не случится.
