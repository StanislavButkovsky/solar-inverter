// Журнал перезагрузок: почему модуль перезапустился и сколько до этого
// проработал. Нужен, чтобы отличить штатное (обновление, команда) от
// плохого (сбой программы, зависание, просадка питания) — без кабеля и
// терминала, по /status бота и странице.
//
// Причина берётся у чипа (esp_reset_reason). Программная перезагрузка у
// чипа одна на все случаи, поэтому перед ESP.restart() модуль сам
// подписывает её: bootMark("обновление прошивки"). Подпись и время работы
// живут в RTC-памяти — она переживает перезагрузку, но не пропажу питания;
// поэтому после выключения «сколько работал» неизвестно.
//
// Последние 10 записей — в NVS; время записи проставляется, когда
// появляются часы (NTP, DS3231 или телефон).
#pragma once
#include <Arduino.h>

void   bootStart();               // в самом начале setup()
void   bootLoop();                // из loop(): время работы, дата записи
void   bootMark(const char* why); // перед ESP.restart()
String bootReason();              // причина этой загрузки, по-русски
bool   bootWasBad();              // сбой, зависание или просадка питания
String bootJson();                // {"reason":…,"bad":…,"prevUpS":…,"list":[…]}
String bootText();                // для бота: причина и последние перезагрузки
