// Журнал событий: кольцевой буфер в памяти.
//
// «Пропала сеть» и «батарея отвалилась» — это не состояние, а событие: важно
// не только что сейчас, но и когда это случилось и сколько раз за сутки.
// Отсюда отдельный журнал, а не поле в снапшоте.
//
// Часть видов заведена заранее под инвертор (пропадание питающей сети, смена
// режима, аварии) — они начнут наполняться, когда появится связь по RS485.
#pragma once
#include <Arduino.h>

enum EventKind : uint8_t {
    EV_BOOT,          // модуль включился
    EV_BMS_UP,        // связь с батареей установлена
    EV_BMS_DOWN,      // связь с батареей потеряна
    EV_BMS_STALE,     // батарея молчит, данные устарели
    EV_FAULT_ON,      // BMS сообщила об аварии
    EV_FAULT_OFF,     // авария снята
    EV_CHG_BLOCKED,   // BMS запретила заряд
    EV_CHG_OK,        // заряд снова разрешён
    EV_DSG_BLOCKED,   // BMS запретила разряд
    EV_DSG_OK,        // разряд снова разрешён
    EV_WIFI_UP,       // модуль вошёл в домашнюю сеть
    EV_WIFI_DOWN,     // модуль потерял домашнюю сеть
    EV_AP_UP,         // поднята точка доступа
    EV_AP_DOWN,       // точка доступа выключена
    EV_GRID_LOST,     // инвертор: пропало питание от сети
    EV_GRID_BACK,     // инвертор: сеть вернулась
    EV_INV_MODE,      // инвертор: сменился режим работы
    EV_INV_FAULT,     // инвертор: авария
    EV_INV_DOWN,      // инвертор: связь потеряна
    EV_INV_UP,        // инвертор: связь установлена
};

// Насколько событие важно: определяет цвет метки в интерфейсе.
enum EventLevel : uint8_t { LV_INFO, LV_WARN, LV_ALARM, LV_GOOD };

void        evAdd(EventKind kind, const char* detail = nullptr);
const char* evText(EventKind kind);
EventLevel  evLevel(EventKind kind);
String      evJson();       // весь журнал, новые сверху
void        evWatchLoop();  // следит за снапшотом и сам заводит события
const char* invModeName(uint8_t mode);
