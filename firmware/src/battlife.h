// Износ батареи: сколько она отработала и не теряет ли ёмкость.
//
// Ток и заряд — от BMS (через инвертор, GBMS): ток точный и со знаком.
//   * А·ч разряда и заряда — интеграл тока, всего (NVS) и по дням
//     (статистика, поле ahOut);
//   * эквивалентные полные циклы = А·ч разряда / ёмкость по BMS;
//   * глубина разряда — по минимуму заряда за день (уже есть в статистике);
//   * оценка ёмкости — по заряду до полного: от заряда ≤ 70 % до 100 %
//     без разряда посередине, А·ч заряда × 100 / (100 − начальный %).
//     Конец отрезка — «полная» по напряжению, которую BMS ставит сама,
//     поэтому оценка показывает реальную ёмкость, а не ту, что в BMS
//     записана. Середину BMS считает током по своей паспортной ёмкости —
//     отсюда погрешность в несколько процентов; смысл — в тренде.
#pragma once
#include <Arduino.h>

void   battStart();
void   battLoop();                // из loop(), раз в секунду
float  battAhOutTotal();          // всего разряда с начала учёта, А·ч
String battJson();                // для страницы
String battText();                // для бота: /battery и сводка 1-го числа
String battMonthText();           // «за прошлый месяц» — в сводку 1-го числа
