// Чтение инвертора через донгл Eybond по Bluetooth LE.
//
// Внутри BLE донгл возит чистый Modbus RTU, без обёртки и без авторизации:
//
//   запрос   [адрес:1][функция:1][регистр:2 BE][количество:2 BE][CRC16:2 LE]
//   ответ    "11111111"[адрес:1][функция:1][байт:1][данные:N][CRC16:2 LE]
//
// Восемь ASCII-единиц в начале ответа надо отрезать, а сам ответ приходит
// несколькими уведомлениями и требует склейки.
//
//   сервис        53300000-0023-4bd4-bbd5-a6920e4c5653
//   53300001-…    запись
//   53300005-…    уведомления
//
// Донгл держит одно соединение: пока к нему подключён модуль, официальное
// приложение к инвертору не подключится, и наоборот.
#pragma once
#include <Arduino.h>

void invStart();                  // подготовить (вызывается из задачи BLE)
void invTick();                   // один шаг: подключиться либо опросить
void invBind(const String& mac);  // привязать донгл и переподключиться
bool invLooksLikeDongle(const String& name, bool hasService);
