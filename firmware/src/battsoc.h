// Свой счёт заряда батареи и предупреждения по её порогам.
//
// Процент BMS считается от ёмкости, записанной в BMS; у первого устройства
// там «75 А·ч просто так», а сборка — б/у ячейки Nissan Leaf ZE0, 14S6P.
// Поэтому плата считает сама:
//   * ампер-часы по току BMS от заданной ёмкости (cfg().bCapAh);
//   * 100 % — средняя ячейка ≥ cfg().bFullMv (4,05 В: так считал владелец и
//     так держал BMS машины), 0 % — ≤ cfg().bEmptyMv (3,40 В под нагрузкой);
//   * в покое (ток < 1 % ёмкости 15 мин) — сверка по напряжению, если счёт
//     ушёл больше чем на 10 %;
//   * измерение ёмкости: ампер-часы между «полной» и «пустой» точками.
// Ёмкость 0 — счёт выключен, процент берётся у BMS как раньше.
//
// Предупреждения — по порогам самой BMS (dalyLimits), когда они прочитаны:
// ячейка у защиты от перезаряда/разряда, выше своего 100 %, на 0 %, разброс,
// заряд на холоде, перегрев. Событием в журнал и строкой в /api/state.
#pragma once
#include <Arduino.h>

void   battSocStart();
void   battSocLoop();             // из loop(), сам раз в секунду
bool   battSocOn();               // свой счёт включён (задана ёмкость)
String battSocJson();             // для страницы: настройки, счёт, измерения, пороги BMS
String battWarnJson();            // ["…", …] — активные предупреждения
// Настройки: ёмкость, 100 % и 0 % на ячейку. Вернёт ошибку или "".
String battSocSet(float capAh, uint16_t fullMv, uint16_t emptyMv);
String battSocSetPct(float pct);  // вручную выставить процент
