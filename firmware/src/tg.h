// Бот: уведомления и команды, без облака — модуль сам ходит в
// api.telegram.org и/или platform-api.max.ru, когда у роутера есть интернет.
// Telegram и MAX — два независимых канала с общими текстами и командами;
// уведомления уходят во все включённые, ответ — туда, откуда спросили.
// Файлы (/csv, /backup, ежемесячная таблица) — только в Telegram.
//
// Настройка: бот создаётся у @BotFather (Telegram) или на business.max.ru
// (MAX), токен вводится в «Настройках»; модуль показывает код из 6 цифр, и
// боту отправляется «/start <код>» (в MAX можно и просто код). После этого
// бот слушает только этот чат.
//
// Уведомления: сеть пропала и вернулась (с длительностью — по тем же
// подтверждённым отключениям, что статистика), батарея ниже порога,
// авария инвертора и её снятие, нет связи с инвертором дольше 5 минут,
// сводка за день в 21:00. Команды: /status /today /outages /help.
//
// Всё сетевое — в отдельной задаче: TLS-рукопожатие и долгий опрос
// getUpdates длятся секундами, держать на них loop() нельзя.
#pragma once
#include <Arduino.h>

void   tgStart();
void   tgLoop();                                 // из loop(): следит за порогами и шлёт
void   tgNotify(const String& text);             // поставить сообщение в очередь
void   tgOutage(bool started, uint32_t seconds); // из статистики: подтверждённое отключение
String tgStateJson();                            // для /api/state
// ch: 0 — Telegram, 1 — MAX. Каналы независимы: можно включить любой или оба.
String tgSetToken(const String& token, uint8_t ch = 0);   // пусто — выключить; вернёт ошибку или ""
void   tgUnbind(uint8_t ch = 0);                 // отвязать чат, выдать новый код
void   tgTest(uint8_t ch = 0);                   // прислать проверочное сообщение
String tgReport(uint8_t what);                   // 1 неделя, 2 месяц, 3 прошлый месяц — для терминала
