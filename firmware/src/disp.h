// Дисплей 2" 240×320 на ST7789 (плата «020-06PS V2.2»), 4-проводный SPI.
//
// Подключение к YD-ESP32-S3: SCL → 12, SDA → 11 (аппаратный SPI чипа),
// CS → 10, DC → 13, RES → 16, BL → 14 (подсветка через транзистор на
// плате дисплея — ШИМом), VDD → 3V3, GND → GND. Выводы от 8/9 (часы),
// 17/18 (RS485) и USB не заняты.
//
// Шесть экранов по кнопке на GPIO 4 (между GPIO 4 и GND): главный, график
// за 24 ч, неделя, итоги, батарея, модуль; через 2 мин без нажатий — снова
// главный. Тревога (нет сети, авария, заряд ниже порога бота) сама
// открывает главный с красной шапкой и включает полную яркость на 10 мин.
//
// Кадр целиком рисуется в PSRAM (150 КБ) и раз в секунду уходит на экран
// в своей задаче: loop() только собирает данные. Дисплей только принимает —
// узнать, подключён ли он, нельзя; без него модуль просто шлёт в пустоту.
// На обычном ESP32 (первое устройство) дисплея нет — заглушки.
//
// Настройки (NVS "disp"): яркость днём и ночью (22–7), гасить через N мин
// без нажатий (0 — никогда), переворот на 180°, инверсия цветов и порядок
// R/B — у разных партий ST7789 они разные.
#pragma once
#include <Arduino.h>

void   dispStart();
void   dispLoop();                         // из loop()
String dispJson();                         // {"on":…,"day":80,"night":15,"flip":0,"inv":1,"bgr":0,"sleep":0}
String dispSet(int day, int night, int flip, int inv, int bgr, int sleep);   // −1 — не менять; "" — сохранено
