// Настройки HS35-5648PRO: что читается и пишется по USB, с ограничениями.
//
// Названия, номера программ на панели, диапазоны и значения по умолчанию —
// из «Руководства по эксплуатации HIDEN HS35» (раздел 3.3, редакция 04.2026),
// для модели 5648PRO (батарея 48 В). Команды G-ASCII — из ha-eybond-local
// (профиль eybond_g_ascii/base.json, запись проверена авторами на LVYUAN
// TY-SIC-3.6KBE, не на HS35). Нумерация кодов у HS35 бывает своей (CHP
// оказался другим), поэтому каждая настройка пишется, только когда её
// чтение сверено с экраном инвертора: отметка «совпадает» на странице.
//
// Напряжения батареи зависят от её типа: у AGM и FLD их инвертор менять не
// даёт, у LIB и CUS диапазоны свои (lo/hi — LIB, cLo/cHi — CUS).
//
// Только с панели (команд в протоколе нет): OPF частота, MDF возврат меню,
// LRS/TRS перезапуск при перегрузке/перегреве, MIP сигнал сбоя питания,
// OLG байпас при перегрузке, EQN выравнивание сейчас, GTI отдача в сеть,
// DBV/DBT второй выход. Не трогаются из модуля нарочно: BAT тип батареи,
// SED сброс к заводским, PAM параллельный режим, удалённое выключение.
#pragma once
#include <Arduino.h>

enum SetKind : uint8_t { SK_ENUM, SK_FLAG, SK_NUM };
enum SetRule : uint8_t {
    SR_NONE,
    SR_BATTV,      // напряжение батареи: только LIB/CUS, диапазон по типу
    SR_EQ,         // выравнивающая зарядка: не для литиевой
    SR_LLV,        // нижний порог сети: диапазон зависит от MOD (APP/UPS)
    SR_READONLY,   // показываем, но из модуля не пишем
};

struct SetDef {
    const char* id;        // ключ для API
    const char* panel;     // как на экране инвертора
    uint8_t     prog;      // номер программы на панели; 0 — не из меню
    const char* group;
    const char* title;
    SetKind     kind;
    const char* rd;        // команда чтения; у флагов — nullptr (читаются TE?/TD?)
    const char* wr;        // префикс записи; у флагов — nullptr
    char        flag;      // буква флага для TE?/TD?/TEx/TDx
    uint8_t     width;     // целое с нулями слева; 0 — дробное с dec знаками
    uint8_t     dec;
    float       lo, hi, step;   // для LIB (или общий)
    float       cLo, cHi;       // для CUS; 0/0 — как у LIB
    float       def;            // по умолчанию у 5648PRO
    const char* unit;
    const char* list;      // допустимые значения через «|», иначе диапазон
    const char* opts;      // подписи вариантов enum через «|», код = номер
    SetRule     rule;
    float       scale;     // показ = сырое / scale (часы → дни); 0 — 1
    const char* note;
};

