// Погода и всё, что от неё зависит: прогноз выработки, сравнение с фактом
// и ночная зарядка от сети, если завтра пасмурно.
//
// Прогноз — Open-Meteo (api.open-meteo.com): бесплатно, без ключа и
// регистрации. Берётся солнечная радиация (Вт/м²) по часам на сегодня и
// завтра и её сумма за сутки. Раз в 3 часа, при ошибке — через 10 минут.
//
// Выработка = сумма радиации за сутки (кВт·ч/м²) × коэффициент панелей.
// Коэффициент учится сам: каждый вечер факт дня делится на радиацию дня,
// из последних 14 дней берётся верхняя четверть — в пасмурные и в дни с
// полной батареей (инвертор придерживает панели) факт ниже возможного, и
// среднее занижало бы прогноз. Пока дней меньше трёх — по мощности панелей
// из настроек (кВт × 0,8), без неё прогноза в кВт·ч нет.
//
// Ночная зарядка: в начале ночного окна (по умолчанию 23:00) — если прогноз
// на ближайший день ниже порога, а CHP стоит PV, ставит PNG; в конце окна
// (7:00) или когда батарея зарядилась до порога — возвращает PV. Трогает
// только то, что поставила сама: CHP, выставленный вручную, не меняет.
//
// TLS на плате один за раз: память под рукопожатие есть только на одно,
// поэтому бот и погода делят tlsLock().
#pragma once
#include <Arduino.h>

void   weatherStart();
void   weatherLoop();            // из loop(): обучение, прогноз в статистику, автоматика
void   weatherRefresh();         // сменились координаты — запросить заново
int    weatherNowRad();          // радиация в этот час по прогнозу, Вт/м²; −1 — неизвестно
float  weatherPvKwh(int8_t day); // прогноз выработки: 0 — сегодня, 1 — завтра; −1 — неизвестно
String weatherJson();            // для /api/state
String weatherText();            // для бота: прогноз и автоматика
bool   weatherChargeActive();    // ночная зарядка сейчас держит CHP = PNG

void   tlsLock();
void   tlsUnlock();
