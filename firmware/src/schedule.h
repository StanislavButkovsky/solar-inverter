// Расписание режимов: «по будням в 7:00 — GRD, в 9:00 — PBG».
//
// Правило — одно переключение в момент: дни недели, время, что ставить
// (OPP или CHP). Интервал — это два правила, начало и конец. До 8 правил,
// хранятся в NVS. Срабатывает раз в сутки, в свою минуту; если инвертор
// занят другим переключением — повторяет до 5 минут. Пропущенное, пока
// модуль был выключен, задним числом не выполняется.
//
// Пока ночная зарядка по прогнозу держит CHP = PNG (weather.cpp), правила
// для CHP пропускаются — иначе они спорили бы друг с другом; бот об этом пишет.
#pragma once
#include <Arduino.h>

void   schedStart();
void   schedLoop();                     // из loop()
String schedJson();                     // {"rules":[{"on":1,"d":31,"h":7,"m":0,"w":0,"c":0}…]}
String schedSave(const String& rules);  // "on.дни.ч.м.что.код;…"; "" — сохранено, иначе ошибка
String schedText();                     // для бота
