// Разведка USB инвертора: что стоит за разъёмом и отвечает ли оно.
//
// Компьютер к инвертору не поднести, поэтому `lsusb` делает сама плата.
// Устройство подключили — она читает его дескрипторы, по ним выбирает,
// как с ним говорить (мост CH34x, CP210x, CDC-ACM или HID), и пробует
// безобидные запросы чтения: Modbus на 19200 и 9600, команду QPI Voltronic.
// Всё, что увидела, складывает текстом в NVS: отчёт переживает отключение
// питания и читается потом страницей, терминалом или дома через порт COM.
//
// Ничего не пишет в инвертор: только чтение регистров и команды-вопросы.
#pragma once
#include <Arduino.h>

void        usbProbeStart();      // поднять USB-хост и ждать устройство
String      usbProbeReport();     // последний отчёт; пусто — ещё ни разу не было
const char* usbProbeState();      // "wait" — ждёт, "busy" — разведка идёт, "done" — готово
uint32_t    usbProbeCount();      // сколько раз устройство подключали за всё время
