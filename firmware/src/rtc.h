// Часы реального времени DS3231 на I²C — чтобы время переживало отключение
// питания, а с ним и привязка статистики к календарю, даже без интернета.
//
// Подключение (модуль ZS-042): VCC → 3V3, GND → GND, SDA и SCL — на выводы
// ниже. Подтяжки на модуле есть. Батарейка: LIR2032, либо CR2032 с выпаянным
// резистором подзарядки (на плате «201»), иначе её будут заряжать.
//
// В модуле хранится UTC. Время из него берётся при включении, если своего
// нет; пишется в него, когда время приходит по NTP или с телефона. Модуля
// нет — прошивка работает как без него.
#pragma once
#include <Arduino.h>

#if defined(CONFIG_IDF_TARGET_ESP32S3)
static const int RTC_SDA = 8, RTC_SCL = 9;     // стандартные I²C у ESP32-S3
#else
static const int RTC_SDA = 21, RTC_SCL = 22;   // стандартные у обычного ESP32
#endif

void   rtcStart();            // найти модуль и взять из него время
void   rtcLoop();             // записать время в модуль, когда пришло снаружи
void   rtcTimeSetExternally(); // время задали с телефона или командой — записать
String rtcStatus();           // для status: есть ли модуль и что в нём
String rtcJson();             // для /api/state: из последнего опроса, без I²C
